import 'package:flutter_test/flutter_test.dart';
import 'package:sfedu_econ/core/room_format.dart';

// Правило одно на оба экрана (пары и экзамены): «ауд. » добавляется ТОЛЬКО
// перед номером; именованные площадки («Онлайн», «Moodle», «Креативное
// пр-во») показываются как есть. Бэкенд хранит значение без префикса —
// канцелярия целиком на совести этой функции.
void main() {
  group('formatRoom: номер получает префикс «ауд. »', () {
    test('обычный номер', () {
      expect(formatRoom('118'), 'ауд. 118');
    });

    test('несколько аудиторий через запятую (сессии)', () {
      expect(formatRoom('324, 325'), 'ауд. 324, 325');
    });

    test('номер с буквой', () {
      expect(formatRoom('218а'), 'ауд. 218а');
    });
  });

  group('formatRoom: не-числовые значения — как есть', () {
    test('Онлайн', () {
      expect(formatRoom('Онлайн'), 'Онлайн');
    });

    test('Moodle', () {
      expect(formatRoom('Moodle'), 'Moodle');
    });

    test('именованная аудитория', () {
      expect(formatRoom('Креативное пр-во'), 'Креативное пр-во');
    });

    test('корпус Г', () {
      expect(formatRoom('Г-138'), 'Г-138');
    });

    test('адрес другой площадки', () {
      expect(
        formatRoom('г.Таганрог, ул.Энгельса, 1 Г-215'),
        'г.Таганрог, ул.Энгельса, 1 Г-215',
      );
    });

    test('пустая строка не превращается в «ауд. »', () {
      expect(formatRoom(''), '');
    });
  });
}
