/// Отображение аудитории — одно правило на карточку пары и карточку экзамена.
///
/// Бэкенд хранит значение без канцелярии («118», «Г-138», «Онлайн»,
/// «Креативное пр-во»), а префикс «ауд. » дописывается здесь — и ТОЛЬКО перед
/// номером. «ауд. Онлайн» и «ауд. Moodle» — бессмыслица, которую эта функция
/// и лечит; держать правило в двух экранах порознь — снова разъедутся.
String formatRoom(String room) {
  if (room.isEmpty) return room;
  final first = room.codeUnitAt(0);
  final startsWithDigit = first >= 0x30 && first <= 0x39; // '0'–'9'
  return startsWithDigit ? 'ауд. $room' : room;
}
