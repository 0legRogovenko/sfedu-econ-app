"""Нормализация аудитории: одно правило для пар (cells) и экзаменов (exams).

Источник пишет одну и ту же аудиторию вразнобой: «ауд.118», «ауд. 118»,
«а.118», «ауд..405» (двойная точка), «118» голым числом. Хранить это как есть —
заставить каждый экран угадывать, есть ли уже префикс (карточка добавляла своё
«ауд. » и показывала «ауд. ауд.118»). Поэтому канцелярский префикс срезается
ЗДЕСЬ, при разборе: в БД лежит голое значение («118», «Г-138», «Креативное
пр-во», «Онлайн»), а слово «ауд.» — забота интерфейса.

Срезается ТОЛЬКО ведущий «ауд»/«а» с точками и пробелами; остальное — как в
источнике. Адреса («г.Таганрог, ул.Энгельса, 1 Г-215») начинаются с «г.»/«ул.»
и правилом не задеваются. cell_raw это не трогает — сырец для админа цел.
"""

from __future__ import annotations

import re

# «ауд.», «Ауд. », «а.», «ауд..» — точка обязательна: без неё «а» — это буква,
# а не сокращение, и слова вроде «Аудитория N» под правило не попадают.
_PREFIX = re.compile(r"^(?:ауд|а)\s*\.+\s*", re.IGNORECASE)


def normalize_room(text: str) -> str:
    """«ауд.118» → «118»; значение без префикса возвращается как есть."""
    stripped = text.strip()
    bare = _PREFIX.sub("", stripped).strip()
    # Вырожденный случай «ауд.» без номера: лучше показать сырец, чем пустоту.
    return bare or stripped
