"""Канонизация магистерских программ: свести разные написания к одному имени.

Одна программа расщепляется между файлами. Файлы расписания дают ЧИСТОЕ имя
(«Корпоративные финансы») и по нему создаётся группа с ПАРАМИ; файлы сессий
дают то же имя в обёртке «Магистерская программа «…»» с опечатками, лишними
пробелами и переносами — и по нему создаётся ОТДЕЛЬНАЯ группа с ЭКЗАМЕНАМИ.
Итог без канонизации: 23 магистерские группы вместо 11, у половины только пары,
у половины только экзамены. canonical_program сводит оба написания к одному из
шести канонических имён — тогда find-or-create по (курс, программа) кладёт пары
и экзамены в одну группу.

Почему фаззи-матч здесь безопасен, а в предметах — запрещён: множество закрытое
(ровно 6 программ) и его элементы далеки друг от друга. Ближайшая программа к
любому грязному написанию — всегда её собственный канон, и он отделён от чужих
десятками правок. У предметов наоборот: близкие имена — это РАЗНЫЕ дисциплины,
и фаззи слил бы их. Поэтому матч принимается, только если РОВНО ОДНА каноническая
программа лежит в пределах порога; иначе (в том числе для незнакомой программы)
строка возвращается как есть — новую программу нельзя молча слить с существующей.
"""

from __future__ import annotations

import re

# Шесть реальных магистерских программ экономфака. Множество закрытое: всё, что
# приходит из файлов, — это одно из шести написанное так или иначе, либо (редко)
# действительно новая программа, которую сливать нельзя.
CANONICAL_PROGRAMS: tuple[str, ...] = (
    "Корпоративные финансы",
    "Учетные технологии и аудит",
    "Экономика труда и управление персоналом",
    "Экономика, управление и право",
    "Экономическая аналитика",
    "International Economics and Analytics (Международная экономика и аналитика)",
)

# «Магистерская программа «Экономическая аналитика»» → снять обёртку, взять ядро.
# Тот же приём, что в structure._MASTER_PROGRAM, но здесь он часть канонизации.
_WRAPPER = re.compile(r"магистерск\w*\s*программ\w*\s*«(.+?)»", re.IGNORECASE)
# Всё, кроме букв (кириллица/латиница) и цифр, при нормализации выкидываем:
# пробелы, дефисы-переносы, кавычки, скобки и пунктуацию.
_NOISE = re.compile(r"[^0-9а-яёa-z]+", re.IGNORECASE)


def canonical_program(raw: str) -> str:
    """Каноническое имя программы или исходная строка, если матч неуверенный.

    Незнакомую программу НЕ форсим в чужую: возвращаем raw. Идемпотентна —
    canonical(canonical(x)) == canonical(x), потому что канон нормализуется сам
    в себя с расстоянием 0.
    """
    if not raw:
        return raw

    target = _normalize(raw)
    if not target:
        return raw

    close = [
        canonical
        for canonical in CANONICAL_PROGRAMS
        if _levenshtein(target, _normalize(canonical)) <= _threshold(canonical)
    ]
    # Уверенный матч — ровно один кандидат в пределах порога. Ноль (незнакомая
    # программа) или два и более (двусмысленность) — не сливаем, отдаём как есть.
    if len(close) == 1:
        return close[0]
    return raw


def _normalize(text: str) -> str:
    """Ядро имени в сравнимом виде: снять обёртку, lowercase, убрать не-буквы/цифры.

    После снятия обёртки «…«ядро»…» остаётся только содержательная часть, а
    выкидывание пробелов/дефисов/кавычек делает опечатки-по-разделителям
    («Корпоративны е», «Корпоратив-ные») неотличимыми от чистого написания.
    """
    match = _WRAPPER.search(text)
    core = match.group(1) if match else text
    return _NOISE.sub("", core).lower()


def _threshold(canonical: str) -> int:
    """Порог правок для канона: 15% длины ядра, но не меньше 3.

    15% берёт короткие описки на длинных именах, минимум 3 — на коротких.
    Программы отстоят друг от друга гораздо дальше порога, поэтому расширить
    его безопасно, а сузить рискованно (перенос + пробел уже дают 2 правки).
    """
    length = len(_normalize(canonical))
    return max(3, round(length * 0.15))


def _levenshtein(a: str, b: str) -> int:
    """Расстояние редактирования: минимум вставок/удалений/замен a → b."""
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    previous = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        current = [i]
        for j, cb in enumerate(b, start=1):
            insert = current[j - 1] + 1
            delete = previous[j] + 1
            substitute = previous[j - 1] + (ca != cb)
            current.append(min(insert, delete, substitute))
        previous = current
    return previous[-1]
