"""Разбор ФИО сотрудника в тройку и короткая форма «Фамилия И.О.».

Порядок слов в данных ЮФУ НЕ единый: справочник кафедр отдаёт «Фамилия Имя
Отчество», а деканат — «Имя Отчество Фамилия». Оба формата попадают в одну
таблицу contacts, поэтому порядок приходится определять по самому ФИО, а не
по источнику записи.

Опознавательный знак — отчество: только оно имеет закрытый набор суффиксов.
Фамилию и имя по виду слова различить нельзя (см. комментарий в parse_person
про «Рабинович»), поэтому позиция отчества и задаёт разбор.
"""

from __future__ import annotations

import re

# Все виды тире, которые встречаются в документах ЮФУ: Word автозаменяет
# ASCII-дефис на типографский, и одна и та же фамилия приезжает то через
# «-», то через «–». Backslash здесь нужен, чтобы строку можно было без
# оговорок подставлять внутрь символьного класса регулярки.
DASH = r"\-‐‑‒–—−"

# Закрытый список суффиксов отчеств. «-ьич» и «-ич» держим отдельно от
# «-ович/-евич»: Ильич, Кузьмич — тоже отчества, но под общий шаблон не идут.
# «-евна» ловит и нестандартное «Володяевна», которое реально есть в штате.
# -ишна: разговорная и старая форма (Никитишна, Ильинишна) — встречается в
# документах. -оглы/-кызы: тюркские отчества, в штате вуза реальны.
# (?i) не годится: регистр значим для определения границ слова в extract.py,
# поэтому капс нормализуется ДО проверки (см. _titlecase).
PATRONYMIC_RE = re.compile(
    r"^[А-ЯЁ][а-яё]*"
    r"(ович|евич|ьич|ич|овна|евна|ична|инична|ишна|оглы|кызы)$"
)

# \s в Python 3 для str-шаблонов покрывает и NBSP (\xa0), и узкий неразрывный
# пробел ( ) — а именно ими сайт факультета разделяет слова в ФИО.
_SPACES_RE = re.compile(r"\s+")
# U+200B/U+200C/U+200D/U+FEFF — нулевой ширины, в \s НЕ входят (isspace() ложь).
# Приезжают при копировании из вёрстки и склеивают ФИО в один токен, из-за
# чего человек молча выпадал из реестра.
_ZERO_WIDTH_RE = re.compile("[\u200b\u200c\u200d\ufeff]")
# Хвостовая пунктуация: источник пишет и «Витальевич,», и «Витальевич.».
_TRAILING_PUNCT_RE = re.compile(r"[\s,;.]+$")
_DASHES_RE = re.compile(f"[{DASH}]")


def _fold(text: str) -> str:
    """Регистр вниз, ё→е.

    «Фёдорова» и «Федорова» в разных источниках — один человек: сайт пишет с
    ё, ведомости почти всегда без неё.
    """
    return text.lower().replace("ё", "е")


def _titlecase(token: str) -> str:
    """«ВОЛЬЧИК» → «Вольчик», «Вольчик» не трогаем.

    Капс приходит и из расписания («ВОЛЬЧИК В.В.» есть в корпусе), и может
    прийти с сайта. extract.py его нормализует, а этот модуль — отвергал:
    асимметрия стоила бы преподавателю всех его пар.
    Дефисные фамилии тоже: «ИЩЕНКО-ПАДУКОВА» → «Ищенко-Падукова».
    """
    if not token.isupper():
        return token
    return re.sub(
        r"[^" + DASH + r"]+",
        lambda part: part.group(0).capitalize(),
        token.lower(),
    ).replace("ё", "ё")


def parse_person(full: str) -> tuple[str, str, str] | None:
    """ФИО → (фамилия, имя, отчество). None, если разобрать нельзя."""
    cleaned = _ZERO_WIDTH_RE.sub(" ", full)
    cleaned = _TRAILING_PUNCT_RE.sub("", cleaned)
    tokens = [_titlecase(t) for t in _SPACES_RE.sub(" ", cleaned).strip().split(" ")]
    if len(tokens) != 3:
        return None

    # Порядок проверок принципиален: индекс 1 РАНЬШЕ индекса 2.
    #
    # Русское личное ИМЯ никогда не оканчивается на -ович/-овна, а ФАМИЛИЯ
    # может: Рабинович, Гринкевич, Абрамович. Поэтому в «Рабинович Иван
    # Петрович» под шаблон отчества подходят ДВА токена из трёх, и наивная
    # проверка «собрать всех кандидатов и потребовать ровно одного» на таких
    # ФИО молча отказывает — человек просто выпадает из справочника.
    #
    # Средний токен же однозначен: отчество в середине бывает только у
    # порядка «Имя Отчество Фамилия». Если он подошёл — это деканатский
    # формат, и никакие фамилии на -ич этого не портят.
    if PATRONYMIC_RE.match(tokens[1]):
        return tokens[2], tokens[0], tokens[1]
    if PATRONYMIC_RE.match(tokens[2]):
        return tokens[0], tokens[1], tokens[2]
    return None


def short_name(full: str) -> str | None:
    """ФИО → «Фамилия И.О.». None, если ФИО не разобралось."""
    parsed = parse_person(full)
    if parsed is None:
        return None
    surname, given, patronymic = parsed
    return f"{surname} {given[0]}.{patronymic[0]}."


def person_key(
    surname: str, given_initial: str, patronymic_initial: str
) -> tuple[str, str, str]:
    """Ключ для сравнения людей из разных источников.

    Фамилия нормализуется агрессивно (регистр, ё, пробелы, ВСЕ виды тире):
    «Ищенко-Падукова», «Ищенко–Падукова» и «Ищенко Падукова» — один человек.
    А вот инициалы режутся до одной буквы и сравниваются как есть: на кафедре
    работают Ласкова Т.С. и Ласкова Д.С., и склеивать их нельзя.
    """
    return (
        _DASHES_RE.sub("", _SPACES_RE.sub("", _fold(surname))),
        _fold(given_initial.strip())[:1],
        _fold(patronymic_initial.strip())[:1],
    )


def key_of_full(full: str) -> tuple[str, str, str] | None:
    """Ключ прямо из полного ФИО. None, если ФИО не разобралось."""
    parsed = parse_person(full)
    if parsed is None:
        return None
    return person_key(*parsed)
