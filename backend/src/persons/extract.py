"""Кандидаты «Фамилия И.О.» из сырого текста ячейки расписания.

ПРЕДУПРЕЖДЕНИЕ ВЫЗЫВАЮЩЕМУ: без сверки с реестром сотрудников этот модуль
ФАБРИКУЕТ ЛЮДЕЙ, и часть подделок неотличима от настоящих ФИО.

Форма «слово с заглавной + две заглавные буквы» принадлежит в расписании не
только людям, и отличить их ФОРМОЙ невозможно. Все случаи ниже взяты из живого
корпуса, и все модуль находит НАМЕРЕННО:

    «Дисциплины ВПК»      → «Дисциплины В.П.» — не человек вообще;
    «Погосян АКТРУ»       → «Погосян А.К.»    — фамилия настоящая, а инициалы
                            откушены от названия помещения;
    «Свиридов АСУ»        → «Свиридов А.С.»   — ХУДШИЙ случай: в штате ЮФУ есть
                            живой Свиридов А.С., и занятие припишется ЧУЖОМУ
                            человеку. Реестр такое НЕ отсеет — кандидат в нём
                            есть;
    «Микроэкономика Н.Н.» → «Микроэкономика Н.Н.» — «В.Н.»/«Н.Н.» это маркеры
                            верхней/нижней недели, от инициалов неотличимы.

Отсюда контракт: find_names() возвращает КАНДИДАТОВ, а не преподавателей.
Решение принимает вызывающий код, сверяя ключ кандидата с реестром:

    from src.persons.names import key_of_full, person_key

    known = {k for k in map(key_of_full, registry_full_names) if k is not None}
    people = [c for c in find_names(cell) if person_key(*c) in known]

Ужесточать шаблон ЗДЕСЬ бессмысленно: «Свиридов А.С.» безупречен по форме, а
любое сужение выкинет живые ФИО — источник пишет их как попало («Буров О.Н»
без точки, «Гриднев Д.С..» с двумя, «Калачев В.Ю.онл» слипшимся с пометкой,
«ВОЛЬЧИК В.В.» капсом). Терять настоящего преподавателя дороже, чем принести
лишнего кандидата, которого отбросит реестр.
"""

from __future__ import annotations

import re

from src.persons.names import DASH, person_key

# Фамилия: «Никитаева» ИЛИ «ВОЛЬЧИК» — в корпусе есть оба написания.
_SUR = r"(?:[А-ЯЁ][а-яё]+|[А-ЯЁ]{2,})"

_NAME_RE = re.compile(
    # Слева от фамилии не должно быть буквы или тире.
    #
    # ЦЕНА ЭТОГО УСЛОВИЯ, замеренная сравнительным прогоном: от выделения
    # «Медянцева Т.К.» из хвоста «Кривошеева-Медянцева Д.Д.» защищает НЕ оно, а
    # жадность фамилии ниже (совпадение съедает двойную фамилию целиком, а
    # finditer не выдаёт пересечений). Единственное, что условие реально
    # меняет, — теряет фамилию, слипшуюся с предыдущим словом или тире:
    # «онлИванов И.И.», «Иванов И.И.-Петров П.П.» дадут на одного человека
    # меньше. В корпусе такого склеивания слева не встретилось (склейка бывает
    # СПРАВА: «Калачев В.Ю.онл»), поэтому условие оставлено как страховка
    # инварианта «двойная фамилия — один человек» на случай правок шаблона.
    # Тест test_glued_prefix_is_a_known_tradeoff фиксирует цену.
    rf"(?<![А-Яа-яЁё{DASH}])"
    # Фамилия, возможно составная. Повтор именно «*», а не «?»: тройные фамилии
    # существуют, а с «?» «Кривошеева-Медянцева-Петрова Д.Д.» не разбиралась
    # ВООБЩЕ (шаблон не дотягивался до инициалов и человек молча пропадал).
    # Пробелы вокруг тире — след переноса строки: «Кривошеева-\nМедянцева»
    # после collapse_spaces даёт «Кривошеева- Медянцева».
    rf"({_SUR}(?:\s*[{DASH}]\s*{_SUR})*)"
    # Инициалы. Точки везде необязательны и могут задваиваться: источник пишет
    # «О.Н», «Д.С..», «Е.В» — требовать точку значит терять эти ФИО.
    rf"\s*([А-ЯЁ])\s*\.?\s*([А-ЯЁ])\s*\.{{0,2}}"
    # Справа не должно быть строчной буквы. Отсекает не ФИО, а ЛИШНЕЕ: в
    # «Калачев В.Ю.онл» и «Маслюкова Е.В ауд.219.» движок откатит точку и
    # пробел, чтобы совпадение кончилось на инициале, а хвост остался целым.
    rf"(?![а-яё])"
)

_SPACES_RE = re.compile(r"\s+")
_DASH_SPLIT_RE = re.compile(rf"\s*[{DASH}]\s*")


def collapse_spaces(text: str) -> str:
    """Схлопнуть любой пробельный мусор в один обычный пробел.

    Обязательна перед разбором: в узкой ячейке PDF двойная фамилия рвётся
    переносом строки («Кривошеева-\\nМедянцева Д.Д.»), а слова местами
    разделены NBSP. Без схлопывания половина фамилии просто теряется.

    Экспортируется, потому что позиции из find_name_spans считаются по
    схлопнутому тексту и к исходной строке НЕ применимы.
    """
    return _SPACES_RE.sub(" ", text)


def find_names(text: str) -> list[tuple[str, str, str]]:
    """Кандидаты (фамилия, инициал имени, инициал отчества) в порядке текста.

    Повторы убраны. ЭТО КАНДИДАТЫ, А НЕ ЛЮДИ — см. докстринг модуля.
    """
    seen: set[tuple[str, str, str]] = set()
    names: list[tuple[str, str, str]] = []
    for _, _, name in find_name_spans(text):
        # Повтор ищем по ключу из names.py, а не по самой тройке: «Фёдорова
        # И.И.» и «Федорова И.И.» в одной ячейке — один человек, и дважды в
        # расписании он стоять не должен. В результат идёт написание,
        # встреченное первым, — гадать, какое из двух «правильное», нечем.
        key = person_key(*name)
        if key not in seen:
            seen.add(key)
            names.append(name)
    return names


def find_name_spans(text: str) -> list[tuple[int, int, tuple[str, str, str]]]:
    """Кандидаты с их положением: (начало, конец, (фамилия, И, О)).

    Нужно, чтобы резать ячейку на предметы по границам ФИО.

    ВАЖНО: границы считаются по collapse_spaces(text), а НЕ по исходной строке —
    схлопывание сдвигает индексы. Вызывающий код обязан резать ТУ ЖЕ схлопнутую
    строку, иначе срез уедет ровно на число съеденных пробелов.

    Повторы здесь НЕ убираются: для сегментации важно каждое вхождение.
    """
    collapsed = collapse_spaces(text)
    return [
        (
            match.start(),
            match.end(),
            (_capitalize_surname(match.group(1)), match.group(2), match.group(3)),
        )
        for match in _NAME_RE.finditer(collapsed)
    ]


def _capitalize_surname(raw: str) -> str:
    """«ВОЛЬЧИК» → «Вольчик», «Кривошеева- Медянцева» → «Кривошеева-Медянцева».

    Капс приводится к обычному виду, потому что одна и та же фамилия в корпусе
    попадается и капсом, и нормально («ВОЛЬЧИК В.В.» и «Вольчик В.В.»), а
    показывать это пользователю как двух людей нельзя.

    Тире любого вида схлопывается в ASCII-дефис вместе с пробелами вокруг:
    пробелы остались от переноса строки, а типографское тире — от автозамены
    Word, и ни то ни другое не является частью фамилии.
    """
    return "-".join(part.capitalize() for part in _DASH_SPLIT_RE.split(raw))
