def _all_articles() -> list[dict]:
    return _APP_ARTICLES + _FACULTY_ARTICLES + _OFFICIAL_ARTICLES


def upsert() -> None:
    session = SessionLocal()
    try:
        created = updated = unchanged = 0
        for a in _all_articles():
            row = session.scalar(select(KbArticle).where(KbArticle.slug == a["slug"]))
            if row is None:
                session.add(
                    KbArticle(slug=a["slug"], title=a["title"], body_md=a["body"])
                )
                created += 1
            elif row.title != a["title"] or row.body_md != a["body"]:
                row.title = a["title"]
                row.body_md = a["body"]
                updated += 1
            else:
                unchanged += 1
        session.commit()
        print(
            f"KB: +{created} новых, {updated} обновлено, {unchanged} без "
            f"изменений; всего в наборе {len(_all_articles())}."
        )
    finally:
        session.close()


if __name__ == "__main__":
    upsert()
