"""Нормализация аудитории: срезаем канцелярский префикс «ауд.»/«а.».

Источник пишет одно и то же четырьмя способами («ауд.118», «а.118»,
«ауд..118», «118»), а Flutter-карточка добавляла свой префикс поверх — выходило
«ауд. ауд.118». Правило одно: ведущий «ауд»/«а» с точками/пробелами срезать,
остальное не трогать. Все литералы — из distinct Lesson.room / ExamEvent.room
живой базы, а не выдуманы.
"""

from __future__ import annotations

import pytest

from src.schedule.rooms import normalize_room


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        # основной корпус: «ауд.» вплотную и с пробелом
        ("ауд.118", "118"),
        ("ауд. 407", "407"),
        # краткая форма «а.»
        ("а.218", "218"),
        # опечатка источника: двойная точка
        ("ауд..405", "405"),
        # регистр не важен
        ("Ауд.118", "118"),
        # именованные аудитории — префикс уходит, имя остаётся целиком
        ("ауд.Креативное пр-во", "Креативное пр-во"),
        ("ауд. Креативное", "Креативное"),
        ("ауд.Кр.пр-во", "Кр.пр-во"),
        # корпус Г: и голый, и с префиксом
        ("ауд.Г-138", "Г-138"),
        ("ауд. Г-401", "Г-401"),
        # хвостовая точка — не наша забота, режем только ведущий префикс
        ("ауд.219.", "219."),
        # несколько аудиторий в одной ячейке (сессии)
        ("ауд.324, 325", "324, 325"),
    ],
)
def test_prefix_is_stripped(raw, expected):
    assert normalize_room(raw) == expected


@pytest.mark.parametrize(
    "raw",
    [
        # без префикса — как есть
        "118",
        "Г-138",
        "Онлайн",
        "онлайн",
        "Moodle",
        "Microsoft Teams",
        "324, 325",
        # адреса начинаются с «г.»/«ул.» — это НЕ префикс аудитории
        "г.Таганрог, ул.Энгельса, 1 Г-215",
        "г.Ростов-на-Дону, ул.М.Горького, 88 ауд.405",
    ],
)
def test_value_without_prefix_is_untouched(raw):
    assert normalize_room(raw) == raw
