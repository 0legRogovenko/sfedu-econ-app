class TestSpans:
    """Позиции нужны, чтобы резать ячейку на предметы."""

    def test_spans_point_at_the_names(self):
        raw = "Бутова С.В. / Писанка С.А."
        spans = find_name_spans(raw)
        assert [raw[start:end] for start, end, _ in spans] == [
            "Бутова С.В.",
            "Писанка С.А.",
        ]

    def test_spans_are_offsets_into_collapsed_text(self):
        # Схлопывание съедает лишние пробелы и сдвигает индексы. Резать нужно
        # collapse_spaces(text) — по исходной строке те же границы уедут.
        raw = "Иванов  И.И.\nПетров П.П."
        collapsed = collapse_spaces(raw)
        spans = find_name_spans(raw)

        assert [collapsed[start:end] for start, end, _ in spans] == [
            "Иванов И.И.",
            "Петров П.П.",
        ]
        # Тот же срез по сырой строке — уже мусор: это и есть причина, по
        # которой collapse_spaces вынесена в экспорт.
        first_start, first_end, _ = spans[1]
        assert raw[first_start:first_end] != "Петров П.П."

    def test_repeats_are_kept_in_spans(self):
        # find_names схлопывает повторы, а сегментации нужно каждое вхождение.
        spans = find_name_spans("Иванов И.И. Иванов И.И.")
        assert len(spans) == 2
        assert {name for _, _, name in spans} == {("Иванов", "И", "И")}


class TestIdentityFabrication:
    """Модуль ОБЯЗАН находить этих «людей» — и именно поэтому нужен реестр.

    Отличить перечисленное от настоящих ФИО по форме НЕЛЬЗЯ. Тесты фиксируют
    поведение по контракту: если кто-то «почистит» шаблон и они позеленеют
    пустым результатом — вместе с мусором уедут живые преподаватели, а
    вызывающий код решит, что сверка с реестром больше не обязательна.
    """

    def test_abbreviation_becomes_a_nonexistent_person(self):
        # «ВПК» — не инициалы, и «Дисциплины» — не фамилия. Отсеет только реестр.
        assert find_names("Дисциплины ВПК") == [("Дисциплины", "В", "П")]

    def test_abbreviation_after_real_surname_fabricates_a_real_person(self):
        # ХУДШИЙ случай: Свиридов А.С. существует и есть в реестре. Фильтр по
        # реестру эту подделку ПРОПУСТИТ, и занятие уедет чужому человеку.
        # Спасает только то, что «АСУ» — аббревиатура кафедры, а не инициалы:
        # разбирать её должен вызывающий код, знающий контекст ячейки.
        assert find_names("Свиридов АСУ") == [("Свиридов", "А", "С")]

    def test_room_name_supplies_the_initials(self):
        # «Погосян АКТРУ»: фамилия настоящая, инициалы откушены от помещения.
        assert find_names("Погосян АКТРУ") == [("Погосян", "А", "К")]

    def test_week_marker_is_indistinguishable_from_initials(self):
        # «В.Н.»/«Н.Н.» — верхняя/нижняя неделя. Прилипнув к предыдущему слову
        # с заглавной, они дают безупречного по форме кандидата.
        assert find_names("Микроэкономика Н.Н.") == [("Микроэкономика", "Н", "Н")]
        assert find_names("Эконометрика В.Н.") == [("Эконометрика", "В", "Н")]

    def test_week_marker_alone_is_not_matched(self):
        # Само по себе «Н.Н.» не ловится: фамилия короче двух букв не бывает.
        # Это не защита, а совпадение — полагаться на него нельзя.
        assert find_names("экономика фирмы Н.Н.") == []

    def test_caps_acronym_splits_into_a_fake_name(self):
        # «АКТРУ» после настоящего ФИО распадается на «Акт» + «Р.У.». Живое ФИО
        # при этом извлекается верно — мусор едет прицепом и гасится реестром.
        assert find_names("Беликова С.А. Г-217 АКТРУ") == [
            ("Беликова", "С", "А"),
            ("Акт", "Р", "У"),
        ]
