"""Извлечение ФИО из ячейки расписания — на живом мусоре ЮФУ.

Все литералы взяты из реальных ячеек, а не придуманы. Защищают две разные
вещи:

1. ПОЛНОТА. Источник пишет ФИО как попало: точка пропущена, задвоена, слиплась
   с пометкой, фамилия разорвана переносом строки, разделитель между людьми —
   то запятая, то слэш, то ПРОСТО ПРОБЕЛ. Каждый такой случай, если его не
   ловить, тихо теряет преподавателя из расписания.

2. ЧЕСТНОСТЬ ГРАНИЦ. Модуль обязан находить и заведомый мусор («Дисциплины
   В.П.»), потому что отличить его формой нельзя. Тесты класса «фабрикация
   личности» фиксируют это как поведение по контракту: они падают, если
   кто-то решит «почистить» шаблон и тем самым создаст иллюзию, что фильтр по
   реестру больше не нужен.
"""

from __future__ import annotations

import pytest

from src.persons.extract import collapse_spaces, find_name_spans, find_names


class TestDirtyPunctuation:
    """Точки вокруг инициалов: пропущены, задвоены, слиплись с хвостом."""

    @pytest.mark.parametrize(
        ("raw", "expected"),
        [
            # точки на месте — базовый случай
            ("Долгова О.И.(с)", ("Долгова", "О", "И")),
            # последней точки нет
            ("Буров О.Н", ("Буров", "О", "Н")),
            ("Архипова К.Э", ("Архипова", "К", "Э")),
            # точка задвоена
            ("Гриднев Д.С..", ("Гриднев", "Д", "С")),
            # пометка о формате слиплась с инициалом без пробела
            ("Калачев В.Ю.онл", ("Калачев", "В", "Ю")),
            # точки нет, дальше аудитория
            ("Маслюкова Е.В ауд.219.", ("Маслюкова", "Е", "В")),
            # адрес с «М.» — одиночная буква фамилией быть не может
            ("Чернова О.А. ул.М.Горького", ("Чернова", "О", "А")),
        ],
    )
    def test_single_name_survives_punctuation(self, raw, expected):
        assert find_names(raw) == [expected]

    def test_uppercase_surname_is_normalized(self):
        # Капс встречается наравне с обычным написанием. Не привести регистр —
        # показать одного человека дважды.
        assert find_names("ВОЛЬЧИК В.В.") == [("Вольчик", "В", "В")]


class TestSeparators:
    """Между людьми в ячейке стоит что угодно, в том числе ничего."""

    @pytest.mark.parametrize(
        ("raw", "expected"),
        [
            # запятая — самый частый разделитель
            (
                "Никитаева А.Ю., Ковалев Д.В.",
                [("Никитаева", "А", "Ю"), ("Ковалев", "Д", "В")],
            ),
            (
                "Маличенко И.П., Постникова В.П., Осипова И.В.",
                [
                    ("Маличенко", "И", "П"),
                    ("Постникова", "В", "П"),
                    ("Осипова", "И", "В"),
                ],
            ),
            # слэш
            (
                "Бутова С.В. / Писанка С.А.",
                [("Бутова", "С", "В"), ("Писанка", "С", "А")],
            ),
            # разделителя нет вовсе — только пробел
            (
                "Остапенко И.И. Осипова И.В.",
                [("Остапенко", "И", "И"), ("Осипова", "И", "В")],
            ),
            # запятая при пропущенной точке (текст экзамена)
            (
                "Туманян Ю.Р, Погосян Н.В.",
                [("Туманян", "Ю", "Р"), ("Погосян", "Н", "В")],
            ),
        ],
    )
    def test_all_names_are_found(self, raw, expected):
        assert find_names(raw) == expected


class TestHyphenatedSurname:
    """Двойная фамилия — источник разрыва одного человека на двух."""

    def test_line_break_inside_surname(self):
        # Узкая ячейка PDF рвёт фамилию переносом. Без схлопывания пробелов
        # уцелела бы только «Медянцева Д.Д.» — то есть ДРУГОЙ человек.
        assert find_names("Кривошеева-\nМедянцева Д.Д.") == [
            ("Кривошеева-Медянцева", "Д", "Д")
        ]

    def test_adjacent_simple_and_hyphenated_are_two_people(self):
        # На кафедре есть и Медянцева Т.К., и Кривошеева-Медянцева Д.Д.
        # Хвост двойной фамилии НЕ должен дать третьего, ложного «Медянцева».
        assert find_names("Медянцева Т.К. Кривошеева-Медянцева Д.Д.") == [
            ("Медянцева", "Т", "К"),
            ("Кривошеева-Медянцева", "Д", "Д"),
        ]

    def test_typographic_dash_is_the_same_person(self):
        # Word автозаменяет дефис на тире; в реестре фамилия через ASCII-дефис.
        assert find_names("Кривошеева–Медянцева Д.Д.") == [
            ("Кривошеева-Медянцева", "Д", "Д")
        ]

    def test_triple_surname_is_taken_whole(self):
        # Шаблон допускает ЛЮБОЕ число частей, а не одну «вторую половину».
        # С единственной необязательной частью тройная фамилия не разбиралась
        # вообще: до инициалов шаблон не дотягивался, человек молча пропадал, а
        # снятие защиты слева вместо этого рождало ложную «Медянцева-Петрова».
        assert find_names("Кривошеева-Медянцева-Петрова Д.Д.") == [
            ("Кривошеева-Медянцева-Петрова", "Д", "Д")
        ]

    def test_separate_surname_after_double_one(self):
        # Пробел вместо второго тире — это уже ДРУГОЙ человек, и фамилия перед
        # ним без инициалов остаётся неопознанной (а не приклеивается).
        assert find_names("Кривошеева-Медянцева Петрова Д.Д.") == [
            ("Петрова", "Д", "Д")
        ]

    def test_glued_prefix_is_a_known_tradeoff(self):
        # ЗАФИКСИРОВАННАЯ ЦЕНА защиты слева (см. комментарий в extract.py):
        # фамилия, слипшаяся с предыдущим словом или тире, НЕ извлекается.
        # В корпусе такой склейки не встретилось, но если встретится — вот
        # падающий тест, по которому защиту можно осознанно снять.
        assert find_names("Иванов И.И.-Петров П.П.") == [("Иванов", "И", "И")]


